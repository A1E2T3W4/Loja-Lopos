export const IDIOMAS = [
  { code:"pt", nome:"Português", flag:"🇵🇹" },
  { code:"en", nome:"English",   flag:"🇬🇧" },
  { code:"ru", nome:"Русский",   flag:"🇷🇺" },
  { code:"fr", nome:"Français",  flag:"🇫🇷" },
];

export const I18nContext = createContext(null);

export const I18nProvider = ({ children }) => {
  const [idioma, setIdiomaState] = useState(
    () => localStorage.getItem("lopos-idioma") || "pt"
  );

  const setIdioma = (codigo) => {
    if (!IDIOMAS.find(i => i.code === codigo)) return;
    setIdiomaState(codigo);
    localStorage.setItem("lopos-idioma", codigo);
  };

  const t = useCallback((chave, params = {}) => {
    let texto = TRADUCOES[idioma]?.[chave] ?? TRADUCOES["pt"]?.[chave] ?? chave;
    Object.keys(params).forEach(p => {
      texto = texto.replace(new RegExp(`\\{${p}\\}`, "g"), params[p]);
    });
    return texto;
  }, [idioma]);

  return (
    <I18nContext.Provider value={{ idioma, setIdioma, t, IDIOMAS, TRADUCOES }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useTranslation = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useTranslation deve ser usado dentro de I18nProvider");
  return ctx;
};

export default I18nProvider;
